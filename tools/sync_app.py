#!/usr/bin/env python3
"""Keep app/heo_designer.html in sync with app/heo_engine.js and app/heo_ui.js.

heo_designer.html is a single self-contained file: it inlines the data payload, the
prediction engine and the interface in one <script> block. The engine and the interface
also exist as standalone files, which are the editable source. Without a check the two
copies drift silently, so the inlined copies are delimited by sentinel comments and
this script rewrites or verifies them.

    python tools/sync_app.py            # rewrite the inlined copies from app/*.js
    python tools/sync_app.py --check    # exit 1 if they differ (used in CI)
"""
import argparse
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HTML = os.path.join(ROOT, "app", "heo_designer.html")
SOURCES = ["heo_engine.js", "heo_ui.js"]

BEGIN = "/* === BEGIN app/{name} — generated by tools/sync_app.py, edit app/{name} === */"
END = "/* === END app/{name} === */"


def _read(path):
    with open(path, encoding="utf-8") as fh:
        return fh.read()


def _span(html, name):
    begin, end = BEGIN.format(name=name), END.format(name=name)
    i, j = html.find(begin), html.find(end)
    if i < 0 or j < 0 or j < i:
        raise SystemExit(f"sentinels for app/{name} not found in app/heo_designer.html")
    return i + len(begin), j


def sync(check=False):
    html = _read(HTML)
    stale = []
    for name in SOURCES:
        source = _read(os.path.join(ROOT, "app", name)).strip()
        start, stop = _span(html, name)
        if html[start:stop].strip() != source:
            stale.append(name)
            html = html[:start] + "\n" + source + "\n" + html[stop:]
    if check:
        if stale:
            print("out of sync with app/heo_designer.html: " + ", ".join(stale))
            print("run: python tools/sync_app.py")
            return 1
        print("app/heo_designer.html is in sync with " + ", ".join(SOURCES))
        return 0
    if stale:
        with open(HTML, "w", encoding="utf-8") as fh:
            fh.write(html)
        print("re-inlined: " + ", ".join(stale))
    else:
        print("already in sync")
    return 0


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="verify only, do not rewrite")
    sys.exit(sync(check=ap.parse_args().check))
